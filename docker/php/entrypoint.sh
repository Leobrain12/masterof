#!/bin/sh
set -e

# APP_KEY/DB_*/итд приходят из env_file: .env в docker-compose.prod.yml (реальные
# переменные окружения контейнера) — не из файла .env внутри образа, там его нет
# (см. .dockerignore). Кэшируется при каждом старте контейнера, а не при сборке
# образа: на моменте сборки .env ещё недоступен, а значения зависят от окружения
# (staging/prod), не должны запекаться в сам образ.
#
# cache_or_warn, не голый artisan-вызов: если конфиг битый (например APP_URL
# без хоста после схемы — "https://" буквально), artisan config:cache падает
# с "Invalid URI". Раньше это (через set -e) валило ВЕСЬ контейнер ещё до
# старта supervisor/php-fpm — контейнер уходил в "exited" без единого шанса
# зайти в терминал и понять, в чём дело (реальный случай, см. vault/Решения.md).
# Теперь падение кэширования — громкое предупреждение в лог, не смерть
# контейнера: приложение продолжает работать без кэша (медленнее, но работает
# и, что важнее в моменте сбоя, — доступно для диагностики через терминал).
cache_or_warn() {
    if ! php artisan "$1"; then
        echo "!!! ВНИМАНИЕ: 'php artisan $1' упал (см. ошибку выше) — продолжаю БЕЗ этого кэша." >&2
        echo "!!! Обычно это значит битое значение в .env (чаще всего APP_URL без хоста)." >&2
    fi
}

cache_or_warn config:cache
cache_or_warn route:cache
cache_or_warn view:cache

exec "$@"
