<?php

namespace App\Services\Crm;

use App\Models\Order;

/**
 * ТЗ п.85: абстракция над конкретной CRM, чтобы бизнес-логика (боты, флоу,
 * OrderStatusMachine) никогда не знала, что за CRM на другом конце — только
 * эту абстракцию (ТЗ п.85.1: "Не связывать Telegram handlers напрямую с
 * Bitrix"). Конкретная реализация подключается через CRM_ADAPTER_CLASS
 * (см. config/services.php) — сейчас это LogCrmAdapter, потому что реальной
 * CRM ещё нет, но контракт уже рассчитан на неё.
 */
interface CrmAdapter
{
    /**
     * Отправить текущий снимок заказа в CRM (ТЗ п.86: order id, мастер, статус,
     * даты, диагностика, итог работ, итоговая цена, запчасти, оплата, завершение,
     * гарантия — всё это уже есть на самой модели Order к моменту вызова).
     *
     * @return string|null id заказа на стороне CRM, если он известен/изменился —
     *                      null, если сохранять на Order нечего (например, лог-заглушка).
     *
     * @throws \Throwable при недоступности CRM — вызывающий job (SyncOrderToCrm)
     *                     отвечает за ретраи (ТЗ п.87), адаптер должен просто бросить исключение.
     */
    public function syncOrder(Order $order): ?string;
}
